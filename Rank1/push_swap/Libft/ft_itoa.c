#include "libft.h"

static size_t	ft_nbr_len(int n)
{
	size_t	len;

	len = 1;
	if (n < 0)
		len++;
	while (n <= -10 || 10 <= n)
	{
		n = n / 10;
		len++;
	}
	return (len);
}

char	*ft_itoa(int n)
{
	char	*str;
	size_t	len;
	long	nb;

	len = ft_nbr_len(n);
	str = (char *) malloc(len + 1);
	if (str == NULL)
		return (NULL);
	nb = n;
	str[len] = '\0';
	if (nb == 0)
		str[0] = '0';
	if (nb < 0)
	{
		str[0] = '-';
		nb = -nb;
	}
	while (nb > 0)
	{
		str[--len] = (nb % 10) + '0';
		nb = nb / 10;
	}
	return (str);
}
